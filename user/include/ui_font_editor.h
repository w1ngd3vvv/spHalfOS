static inline uint32_t ui_blend(uint32_t bg, uint32_t fg, uint8_t a) {
    if (a == 0) return bg;
    if (a >= 255) return fg;
    uint32_t inv = 255 - a;
    uint32_t br=(bg>>16)&0xFF, bgc=(bg>>8)&0xFF, bb=bg&0xFF;
    uint32_t fr=(fg>>16)&0xFF, fgc=(fg>>8)&0xFF, fbv=fg&0xFF;
    return (((fr*a+br*inv+127)/255)<<16) | (((fgc*a+bgc*inv+127)/255)<<8) | ((fbv*a+bb*inv+127)/255);
}
