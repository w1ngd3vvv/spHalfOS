static inline int ui_draw_char(uint32_t *fb, int fbw, int fbh, int x, int y, char ch, uint32_t fg, int scale) {
    unsigned char uc = (unsigned char)ch;
    if (uc < 32 || uc > 126) uc = '?';
    const uint8_t (*g)[UI_FONT_MAXW] = ui_font16[uc - 32];
    int adv = ui_font_adv[uc-32]*scale;
    for (int row = 0; row < UI_FONT_H; row++) {
        for (int col = 0; col < UI_FONT_MAXW; col++) {
            uint8_t a = g[row][col];
            if (!a) continue;
            for (int sy = 0; sy < scale; sy++)
                for (int sx = 0; sx < scale; sx++) {
                    int px = x + col*scale+sx, py = y + row*scale+sy;
                    if ((unsigned)px < (unsigned)fbw && (unsigned)py < (unsigned)fbh) {
                        uint32_t *p = &fb[py*fbw+px];
                        *p = ui_blend(*p, fg, a);
                    }
                }
        }
    }
    return adv;
}
